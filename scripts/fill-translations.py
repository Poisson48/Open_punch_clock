def unescape_xml(text: str) -> str:
    return (
        text.replace("&apos;", "'")
        .replace("&quot;", '"')
        .replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&amp;", "&")
    )


def fill_ts(path: Path, locale: str) -> None:
    tree = ET.parse(path)
    root = tree.getroot()
    table = T.get(locale, {})
    for message in root.iter("message"):
        source_el = message.find("source")
        trans_el = message.find("translation")
        if source_el is None or trans_el is None or source_el.text is None:
            continue
        src = unescape_xml(source_el.text)
        if locale == "fr":
            trans_el.text = src
        else:
            trans_el.text = table.get(src, src)
        if "type" in trans_el.attrib:
            del trans_el.attrib["type"]
    tree.write(path, encoding="utf-8", xml_declaration=True)


def main() -> None:
    for ts in sorted(ROOT.glob("openpunchclock_*.ts")):
        locale = ts.stem.replace("openpunchclock_", "")
        fill_ts(ts, locale)
        print(f"filled {ts.name}")


if __name__ == "__main__":
    main()
